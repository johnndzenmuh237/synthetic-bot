def service_worker_js(cache_name, offline_url):
    """Service worker source. Never touches /api/, /socket.io/ or HTML pages (network only)."""
    return """/* generated by pwa.py */
var CACHE = %s;
var OFFLINE = %s;
self.addEventListener('install', function (e) {
  e.waitUntil(caches.open(CACHE).then(function (c) {
    return c.addAll([OFFLINE, '/static/css/style.css']).catch(function () {});
  }).then(function () { return self.skipWaiting(); }));
});
self.addEventListener('activate', function (e) {
  var prefix = CACHE.replace(/-v\\d+$/, '');
  e.waitUntil(caches.keys().then(function (keys) {
    return Promise.all(keys.filter(function (k) { return k.indexOf(prefix) === 0 && k !== CACHE; })
      .map(function (k) { return caches.delete(k); }));
  }).then(function () { return self.clients.claim(); }));
});
self.addEventListener('fetch', function (e) {
  var req = e.request, url = new URL(req.url);
  if (req.method !== 'GET' || url.origin !== self.location.origin) return;
  if (url.pathname.indexOf('/socket.io') === 0 || url.pathname.indexOf('/api/') !== -1 ||
      url.pathname.slice(-4) === '.csv') return;                       /* live data: always the network */
  if (req.mode === 'navigate') {                                       /* pages: network, else the offline note */
    e.respondWith(fetch(req).catch(function () { return caches.match(OFFLINE); }));
    return;
  }
  if (url.pathname.indexOf('/static/') === 0) {                        /* static files: fast, refreshed in background */
    e.respondWith(caches.open(CACHE).then(function (c) {
      return c.match(req).then(function (hit) {
        var net = fetch(req).then(function (r) { if (r && r.ok) c.put(req, r.clone()); return r; })
                            .catch(function () { return hit; });
        return hit || net;
      });
    }));
  }
});
""" % (json.dumps(cache_name), json.dumps(offline_url))


